import { test, expect } from '@playwright/test';

test('profile, account persistence, fees and private documents', async ({ page, browser }) => {
  const email = 'owner-' + Date.now() + '@example.com';
  await page.goto('/');
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Aaryan');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('a-secure-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page).toHaveURL(/\/workspace$/);
  await expect(page.getByText('Saved to your account', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Fees', exact: true }).click();
  await page.getByRole('button', { name: 'Add fee', exact: true }).click();
  await page.getByLabel('Amount', { exact: true }).fill('125.50');
  await expect(page.locator('.fee-totals')).toContainText('$125.50');
  const saved = page.waitForResponse(response => response.url().endsWith('/api/workspace') && response.request().method() === 'PUT' && response.ok());
  await page.getByRole('checkbox', { name: 'Mark Application fee paid' }).check();
  await saved;
  await expect(page.locator('.fee-totals > div').nth(1)).toContainText('$125.50');
  await expect(page.locator('.fee-totals > div').nth(2)).toContainText('$0.00');
  await expect(page.getByText('Saved to your account', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Fees', exact: true }).click();
  await expect(page.getByLabel('Amount', { exact: true })).toHaveValue('125.5');
  await page.screenshot({ path: 'test-results/fees-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Documents', exact: true }).click();
  await page.getByLabel('Upload document').setInputFiles({ name: 'statement.txt', mimeType: 'text/plain', buffer: Buffer.from('My statement of purpose') });
  await expect(page.getByText('statement.txt', { exact: true })).toBeVisible();
  const downloadLink = page.getByRole('link', { name: 'Download statement.txt' });
  const url = await downloadLink.getAttribute('href');
  const download = await page.request.get(url!);
  expect(await download.text()).toBe('My statement of purpose');
  const outsider = await browser.newContext();
  const unauthorized = await outsider.request.get('http://127.0.0.1:5293' + url);
  expect(unauthorized.status()).toBe(401);
  const origin = 'http://127.0.0.1:5293';
  const signup = await outsider.request.post(origin + '/api/auth/sign-up/email', { headers: { Origin: origin }, data: { name: 'Other', email: 'other-' + Date.now() + '@example.com', password: 'another-secure-password' } });
  expect(signup.ok()).toBeTruthy();
  expect((await outsider.request.get(origin + url)).status()).toBe(404);
  expect((await outsider.request.get(origin + '/api/workspace')).status()).toBe(200);
  expect((await (await outsider.request.get(origin + '/api/workspace')).json()).workspace).toBeNull();
  expect((await page.request.delete(url!, { headers: { Origin: 'https://untrusted.example' } })).status()).toBe(403);
  await outsider.close();
  await page.getByRole('button', { name: 'Delete statement.txt' }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByText('statement.txt', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.screenshot({ path: 'test-results/profile-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:5293/');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('a-secure-password-123');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/workspace$/);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Fees', exact: true }).click();
  await expect(page.getByLabel('Amount', { exact: true })).toHaveValue('125.5');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/fees-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});
